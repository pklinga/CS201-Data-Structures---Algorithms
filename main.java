import java.util.Scanner;

/**
 * The Binary Search Tree node class
 */

class TreeNode {
    int value;
    TreeNode left;
    TreeNode right;

    public TreeNode(int value) {
        this.value = value;
        this.left = null;
        this.right = null;
    }
}

/**
 * A Binary Search Tree class with the operations
 */

class BinarySearchTree {
    private TreeNode root;

    public BinarySearchTree() {
        this.root = root;
    }

}